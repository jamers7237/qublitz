export function seedFromURL(): number | null {
  if (typeof location === 'undefined') return null;
  const v = new URLSearchParams(location.search).get('seed');
  if (v === null) return null;
  const n = Number(v);
  return Number.isFinite(n) ? n >>> 0 : null;
}

/** New Game: a NEW hidden seed/phase (unless ?seed= pins it for debugging). */
export function startNewGame(name: string, seed?: number) {
  const s = newGameState(name.trim() || 'Wanderer', seed ?? seedFromURL() ?? randomSeed());
  gameStore.set(s);
  const debug = uiStore.get().debug;
  uiStore.set({ ...initialUI(), screen: 'game', debug });
  logAction(`new game seed=${s.seed}`);
  bus.emit('roomChanged', { room: s.room, spawn: s.spawn });
  say(D.intro(s.playerName));
}

export function continueGame(s: GameState) {
  gameStore.set(s);
  const debug = uiStore.get().debug;
  uiStore.set({ ...initialUI(), screen: 'game', debug });
  logAction(`continue seed=${s.seed}`);
  bus.emit('roomChanged', { room: s.room, spawn: s.spawn });
  syncProgress();
}

/** Restart with the same seed (deterministic repro). */
export function restartSameSeed() {
  const s = gameStore.get();
  startNewGame(s.playerName, s.seed);
}

export type CheckpointKind = 'prologue' | 'midpoint' | 'late' | 'vault';

/**
 * Judge/demo checkpoints. All journal entries here are generated by the REAL engine
 * but are clearly marked source:'archive' and the UI labels them as archival, never live.
 */
export function buildCheckpoint(kind: CheckpointKind, seed: number, name = 'Judge'): GameState {
  const s = newGameState(name, seed);
  s.demo = kind;
  if (kind === 'prologue') return s;
  const archiveShots = kind === 'midpoint' ? 18 : 24;
  for (let i = 1; i <= archiveShots; i++) {
    const { outcome } = sampleNormal(s.phase, streamRng(seed, 'archive', i));
    s.journal.shots.push({ id: s.counters.nextShotId++, timeline: i, outcome, source: 'archive', at: 0 });
  }
  s.timeline.index = archiveShots;
  s.counters.rewinds = archiveShots;
  s.flags.firstRewind = true;
  s.flags.sideQuest = true;
  s.flags.impressions = true;
  s.flags.leverFirst = true;
  s.flags.cabinetIntro = true;
  s.flags.switchboardIntro = true;
  s.inventory.keyItems.push('notebook');
  s.puzzles.notebookMatch.solved = true;
  for (const sensor of SENSORS) {
    s.journal.routes[sensor.address] = { objectId: sensor.id, timeline: 0 };
    s.manual[sensor.address - 1] = { route: addressToRoute(sensor.address), object: sensor.id, zero: sensor.zero.key, notes: 'archived demo entry' };
  }
  s.puzzles.calibration = { slot: 'X', measuredEmpty: true, lastResult: 1, runs: 2, solved: true };
  s.puzzles.listening.labels = { 2: 'voice', 3: 'voice', 4: 'height', 5: 'height', 6: 'height', 7: 'breath', 8: 'breath' };
  s.puzzles.listening.solved = true;
  s.puzzles.switchboard.solved = ['r1', 'r2', 'r3'];
  if (kind === 'late' || kind === 'vault') {
    s.puzzles.mirror = { rot: [2, 0, 0], solved: true };
    s.inventory.keyItems.push('cartridge');
    const echoes = kind === 'late' ? 10 : 16;
    for (let i = 1; i <= echoes; i++) {
      const bit = sampleEcho(s.phase, streamRng(seed, 'archive-echo', i));
      s.journal.echoes.push({ id: s.counters.nextShotId++, timeline: archiveShots + i, bit, source: 'archive', at: 0 });
    }
    s.timeline.index += echoes;
    s.puzzles.ledger.found = true;
    s.puzzles.ledger.clues = ['hooks', 'trash', 'couch', 'clock'];
  }
  if (kind === 'vault') {
    s.puzzles.ledger.assign = { 2: 2, 3: 3, 4: 5, 5: 7 };
    s.puzzles.ledger.solved = true;
    s.puzzles.toaster = { step: 2, unlocked: true };
  }
  return s;
}

export function loadCheckpoint(kind: CheckpointKind, seed?: number) {
  const s = buildCheckpoint(kind, seed ?? gameStore.get().seed);
  continueGame(s);
  say([{ text: `DEMO CHECKPOINT (${kind.toUpperCase()}). The notebook holds ARCHIVED results generated earlier by the same engine. They are labelled as archive, not live. Walk in from the hallway for a fresh live shot.` }]);
}
